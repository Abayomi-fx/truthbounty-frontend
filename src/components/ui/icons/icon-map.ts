/**
 * UI-FE-089 — Approved Icon Map (dynamic path)
 *
 * Maps every approved {@link IconName} to its concrete glyph. This module is
 * only pulled in by the dynamic `<Icon name=… />` component. Consumers that
 * render a single, statically-known icon should import it from `selective.ts`
 * instead so the unused registry is tree-shaken away.
 */

